-- +goose Up
-- Hosts are known by their machine ID (or hostname, if they have none).
-- Milestone 3 puts them into environments.
CREATE TABLE hosts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id     TEXT    NOT NULL UNIQUE,
    name           TEXT    NOT NULL,
    hostname       TEXT    NOT NULL,
    os             TEXT    NOT NULL DEFAULT '',
    platform       TEXT    NOT NULL DEFAULT '',
    kernel         TEXT    NOT NULL DEFAULT '',
    arch           TEXT    NOT NULL DEFAULT '',
    cpu_model      TEXT    NOT NULL DEFAULT '',
    cores          BIGINT NOT NULL DEFAULT 0,
    mem_total      BIGINT NOT NULL DEFAULT 0,
    boot_time      BIGINT NOT NULL DEFAULT 0,
    agent_version  TEXT    NOT NULL DEFAULT '',
    docker_version TEXT    NOT NULL DEFAULT '',
    first_seen     BIGINT NOT NULL,
    last_seen      BIGINT NOT NULL
);

CREATE TABLE filesystems (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id   BIGINT NOT NULL REFERENCES hosts (id) ON DELETE CASCADE,
    mount     TEXT    NOT NULL,
    device    TEXT    NOT NULL DEFAULT '',
    fstype    TEXT    NOT NULL DEFAULT '',
    last_seen BIGINT NOT NULL,
    UNIQUE (host_id, mount)
);

-- A container keeps its row across redeploys: slug is compose project and
-- service (or the container name), docker_id the current container.
CREATE TABLE containers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id         BIGINT NOT NULL REFERENCES hosts (id) ON DELETE CASCADE,
    slug            TEXT    NOT NULL,
    docker_id       TEXT    NOT NULL DEFAULT '',
    name            TEXT    NOT NULL DEFAULT '',
    image           TEXT    NOT NULL DEFAULT '',
    compose_project TEXT    NOT NULL DEFAULT '',
    compose_service TEXT    NOT NULL DEFAULT '',
    state           TEXT    NOT NULL DEFAULT '',
    health          TEXT    NOT NULL DEFAULT '',
    exit_code       BIGINT NOT NULL DEFAULT 0,
    restarts        BIGINT NOT NULL DEFAULT 0,
    started_at      BIGINT NOT NULL DEFAULT 0,
    labels_json     TEXT    NOT NULL DEFAULT '{}',
    first_seen      BIGINT NOT NULL,
    last_seen       BIGINT NOT NULL,
    gone_at         BIGINT,
    UNIQUE (host_id, slug)
);

-- Samples: one row per reading, a column per value. NULL means the value
-- was not measured (rates need two readings).
CREATE TABLE host_samples (
    host_id       BIGINT NOT NULL REFERENCES hosts (id) ON DELETE CASCADE,
    ts            BIGINT NOT NULL,
    cpu           DOUBLE PRECISION,
    iowait        DOUBLE PRECISION,
    steal         DOUBLE PRECISION,
    load1         DOUBLE PRECISION,
    load5         DOUBLE PRECISION,
    load15        DOUBLE PRECISION,
    mem_used      BIGINT,
    mem_available BIGINT,
    swap_used     BIGINT,
    swap_total    BIGINT,
    net_rx        DOUBLE PRECISION,
    net_tx        DOUBLE PRECISION,
    disk_read     DOUBLE PRECISION,
    disk_write    DOUBLE PRECISION,
    uptime        BIGINT,
    PRIMARY KEY (host_id, ts)
);

CREATE TABLE fs_samples (
    filesystem_id BIGINT NOT NULL REFERENCES filesystems (id) ON DELETE CASCADE,
    ts            BIGINT NOT NULL,
    used          BIGINT NOT NULL,
    total         BIGINT NOT NULL,
    inodes_used   BIGINT,
    inodes_total  BIGINT,
    PRIMARY KEY (filesystem_id, ts)
);

CREATE TABLE container_samples (
    container_id BIGINT NOT NULL REFERENCES containers (id) ON DELETE CASCADE,
    ts           BIGINT NOT NULL,
    cpu          DOUBLE PRECISION,
    mem          BIGINT,
    mem_limit    BIGINT,
    net_rx       DOUBLE PRECISION,
    net_tx       DOUBLE PRECISION,
    PRIMARY KEY (container_id, ts)
);

-- What happened to an object: reboots, container starts and deaths, agents
-- coming and going.
CREATE TABLE events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts           BIGINT NOT NULL,
    subject_kind TEXT    NOT NULL,
    subject_id   BIGINT NOT NULL,
    kind         TEXT    NOT NULL,
    data_json    TEXT    NOT NULL DEFAULT '{}'
);
CREATE INDEX events_subject ON events (subject_kind, subject_id, ts);
CREATE INDEX events_ts ON events (ts);

