-- A check of something from outside: http, tls, tcp, or a heartbeat that
-- a job sends. Its key is its environment's path and its slug.
CREATE TABLE checks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id    BIGINT NOT NULL REFERENCES scopes (id),
    container_id      BIGINT REFERENCES containers (id) ON DELETE CASCADE,
    slug              TEXT    NOT NULL,
    path              TEXT    NOT NULL UNIQUE,
    name              TEXT    NOT NULL,
    type              TEXT    NOT NULL CHECK (type IN ('http', 'tls', 'tcp', 'heartbeat')),
    spec_json         TEXT    NOT NULL,
    ping_token_hash   TEXT    UNIQUE,
    ping_token_sealed TEXT,
    state             TEXT    NOT NULL DEFAULT 'unknown',
    state_since       BIGINT,
    last_ping         BIGINT,
    created_at        BIGINT NOT NULL
);
CREATE INDEX checks_environment ON checks (environment_id);

CREATE TABLE check_results (
    check_id       BIGINT NOT NULL REFERENCES checks (id) ON DELETE CASCADE,
    probe_id       BIGINT NOT NULL REFERENCES probes (id) ON DELETE CASCADE,
    ts             BIGINT NOT NULL,
    ok             BIGINT NOT NULL,
    latency_ms     DOUBLE PRECISION,
    status_code    BIGINT,
    cert_not_after BIGINT,
    error          TEXT,
    PRIMARY KEY (check_id, probe_id, ts)
);

